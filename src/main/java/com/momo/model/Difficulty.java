package com.momo.model;


/**
 * 🗺️ 战术身份指针枚举 - 记录单词全生命周期的出身背景与百炼成钢履历
 * <p>
 * 🔄 [全生命周期高精度状态流转图]
 * <pre>
 * 【 0. 未分拣新词大盘 】
 * │
 * ┌─────────────────────┼─────────────────────┐
 * │ (一眼认识)          │ (觉得眼熟)          │ (完全不认识)
 * ▼                     ▼                     ▼
 * ┌──────────────┐      ┌──────────────┐      ┌──────────────┐
 * │  [FROZEN]    │      │  [BURNING]   │      │  [BURNING]   │
 * │INIT_MASTERED │      │  INIT_VAGUE  │      │INIT_STRANGER │
 * │ (自带 5 血)  │      │ (自带 2 血)  │      │ (自带 0 血)  │
 * └──────┬───────┘      └──────┬───────┘      └──────┬───────┘
 * │                     │                     │
 * │                     └──────────┬──────────┘
 * │                                │ (投入大轰炸死磕)
 * │                                ▼
 * │                     ┌─────────────────────────────┐
 * │                     │    【 轰炸机死磕核心区 】   │
 * │                     │  cycleWrongCount ++         │
 * │                     │  reviewCount (加血/归零)    │
 * │                     └──────┬───────────────┬──────┘
 * │                            │               │
 * │     (刷满 5 血飞升毕业)    │               │ (单日连错 >10 次)
 * │     [BURNING]->[FROZEN]    │               │ 触发暴躁熔断
 * │                            ▼               ▼
 * │                 ┌────────────────────┐┌──────────────┐
 * │                 │ 阵营 B：结算法网   ││ [BURNING]    │
 * │                 │ 0错 -> SMOOTH_KILL ││  STUCK_LOOP  │
 * │                 │ 1-3错->NORMAL_KILL ││ (雪藏 24h)   │
 * │                 │ >3错 -> HARD_KILL  │└──────┬───────┘
 * └───────┬─────────┴────────────────────┘       │
 * │                                      │ (24h 后解禁)
 * ▼                                      ▼
 * ┌─────────────────────────────────────────────────────────────┐
 * │                       [FROZEN 熟词舱]                       │
 * │      存放所有通关/秒杀单词。根据不同身份标签，动态计算复习寿命。      │
 * └──────────────────────────────┬──────────────────────────────┘
 * │
 * ┌──────────────────────────┴──────────────────────────┐
 * │ (大盘抽查：用户手动打回)                            │ (引擎复习：破冰抽查答错)
 * ▼                                                     ▼
 * ┌──────────────┐                                      ┌──────────────┐
 * │  [BURNING]   │                                      │  [BURNING]   │
 * │ KILL_RECOUP  │                                      │ REVIVE_FALL  │
 * │ (0血重修)    │                                      │ (惩罚性重修) │
 * └──────┬───────┘                                      └──────┬───────┘
 * │                                                     │
 * └───────────────────────────┬─────────────────────────┘
 * │ (重新滚回)
 * ▼
 * [ 进入大轰炸区重新死磕 ]
 * </pre>
 */
public enum Difficulty {

    // =========================================================================
    // 阵营 A：初始化清洗出身（初次导入分拣时产生）
    // =========================================================================

    /**
     * 初始掌握：用户在第一天导入分拣时，一眼认出并直接秒杀的熟词。
     * 状态机：status = 'FROZEN', reviewCount = 5
     * 战术价值：超长寿命。未来艾宾浩斯引擎做周期性复习时，可设定 60~90 天后才浮现。
     */
    INIT_MASTERED,

    /**
     * 初始模糊：第一天分拣时觉得“似懂非懂、有印象但说不准”的夹生词。
     * 状态机：status = 'BURNING', reviewCount = 2
     * 战术价值：快速唤醒。大轰炸拉取时自带 2 点初始血条，连续答对 3 次即可通关。
     */
    INIT_VAGUE,

    /**
     * 初始陌生：第一天分拣时用户承认完全不会、两眼一抹黑的纯生词。
     * 状态机：status = 'BURNING', reviewCount = 0
     * 战术价值：死穴新词。大轰炸引擎应为其分配最高出现权重，实施饱和曝光。
     */
    INIT_STRANGER,


    // =========================================================================
    // 阵营 B：轰炸机百炼成钢（常规斩杀通关结算时转换）
    // =========================================================================

    /**
     * 顺畅斩杀：在大轰炸死磕历程中，一次都没有错过（cycleWrongCount == 0），行云流水直接打满5枪毕业。
     * 战术价值：高熟练度。短期内极难遗忘，遗忘复习寿命周期可设为 30 天。
     */
    SMOOTH_KILL,

    /**
     * 常规斩杀：在轰炸机里错过，但表现中规中矩（0 < cycleWrongCount <= 3）。
     * 战术价值：标准记忆曲线。维持经典艾宾浩斯复习策略（如 7天、15天 逐级递增复习）。
     */
    NORMAL_KILL,

    /**
     * 惨烈斩杀：硬骨头、顽固死角！死得死去活来（cycleWrongCount > 3），打满5次血条才勉强通关。
     * 战术价值：高危欺骗词！虽然进入冻结舱，但极可能是短期强行记住的。算法应在 3 天内强行解冻重新大轰炸。
     */
    HARD_KILL,


    // =========================================================================
    // 阵营 C：战术收复与解冻逆转（主动/被动回炉产生）
    // =========================================================================

    /**
     * 战术收复：单词处于 FROZEN 舱时，用户在大盘页面自主点验发现生疏，手动“打回重刷”。
     * 状态机：status = 'BURNING', reviewCount = 0, cycleWrongCount = 0
     * 战术价值：主动防御。非答题按错，全局错词不加。作为“主动抓回的漏网之鱼”，轰炸优先级应高于普通新词。
     */
    KILL_RECOUP,

    /**
     * 周期坠落：过了30/60天，复习引擎拉出熟词做“破冰抽查”，用户第一枪就被击落打错。
     * 状态机：status = 'BURNING', reviewCount = 0, cycleWrongCount = 0
     * 战术价值：被动遗忘铁证。重新滚回轰炸机死磕。且该词再次通关结算时，其复习寿命要遭到降级惩罚（如减半）。
     */
    REVIVE_FALL,


    // =========================================================================
    // 阵营 D：异常与卡死保护机制（单次会话熔断保护）
    // =========================================================================

    /**
     * 黑洞卡死（防暴躁熔断）：用户在同一个轰炸会话中对该词连续按错超出阈值（如单日 cycleWrongCount > 10）。
     * 状态机：status = 'BURNING'，但当天动态剥夺大轰炸高频曝光资格
     * 战术价值：疲劳熔断。强行移入“禁闭室”雪藏 24 小时，等用户睡眠后神经元重新巩固再放出来，防止砸键盘。
     */
    STUCK_LOOP
}